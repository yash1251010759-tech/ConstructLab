import React, { useState, useRef, useEffect } from 'react';
import { CircuitData } from '../types/circuit';
import { COMPONENT_CATALOG } from '../utils/circuitEngine';
import { synthesizeLocalCircuit } from '../utils/aiCircuitSynthesizer';
import {
  X,
  Sparkles,
  Send,
  Loader2,
  Trash2,
  Bot,
  User,
  ArrowDownToLine,
  CheckCircle2,
  Copy,
  Check,
  Cpu,
  RefreshCw,
} from 'lucide-react';
import ReactMarkdown from 'react-markdown';

interface AIAssistantModalProps {
  circuit: CircuitData;
  onSynthesizeCircuit: (circuit: CircuitData) => void;
  onClose: () => void;
  isDarkMode: boolean;
}

interface ChatMessage {
  id: string;
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
  circuitPayload?: CircuitData;
}

const QUICK_PROMPTS = [
  '🔍 Explain my canvas circuit',
  '🛠️ Troubleshoot & check for wiring errors',
  '⚡ How does a JK Flip-Flop work?',
  '💡 Build a 2-bit Adder circuit',
  '📊 Explain K-Maps (Karnaugh Maps)',
  '🔢 Explain 2:1 Multiplexer logic',
];

export const AIAssistantModal: React.FC<AIAssistantModalProps> = ({
  circuit,
  onSynthesizeCircuit,
  onClose,
  isDarkMode,
}) => {
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const [copiedId, setCopiedId] = useState<string | null>(null);
  const [loadedCircuitId, setLoadedCircuitId] = useState<string | null>(null);

  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      id: 'welcome',
      role: 'assistant',
      content: `### Welcome to ConstructLab AI Tutor! 🤖⚡
I am your personal **Digital Electronics & Logic Design Assistant**. 

Here is what I can do for you:
- 📖 **Explain circuits**: Ask me how your current canvas circuit or any logic gate operates.
- 🔍 **Debug & Troubleshoot**: Identify floating pins, short circuits, or missing clock pulses.
- 🛠️ **Synthesize Circuits**: Ask me to build a circuit (e.g. *"Build an XOR gate from NAND gates"* or *"Create a 2-bit Adder"*), and I'll generate a diagram you can load directly to your canvas!
- 📐 **Theory & Math**: Boolean algebra, De Morgan's laws, Karnaugh maps, truth tables, and Verilog HDL.

How can I assist you with your circuit today?`,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    },
  ]);

  const messagesEndRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages, loading]);

  useEffect(() => {
    inputRef.current?.focus();
  }, []);

  // Helper to extract JSON circuit from AI response if present
  const extractCircuitFromResponse = (text: string): { cleanText: string; circuit?: CircuitData } => {
    // Matches ```circuit-json ... ``` or ```json ... ``` or raw json with components & wires
    const jsonMatch = text.match(/```(?:circuit-json|json)?\s*([\s\S]*?)\s*```/);
    const candidateJson = jsonMatch ? jsonMatch[1] : null;

    if (candidateJson) {
      try {
        const parsed = JSON.parse(candidateJson);
        if (parsed.components && Array.isArray(parsed.components) && parsed.wires && Array.isArray(parsed.wires)) {
          // Normalize and hydrate components using catalog defaults
          const hydratedComponents = parsed.components.map((c: any) => {
            const type = (c.type || 'AND').toUpperCase();
            const validMeta = COMPONENT_CATALOG[type as keyof typeof COMPONENT_CATALOG] || COMPONENT_CATALOG.AND;
            
            return {
              id: c.id || `comp_${Date.now()}_${Math.random().toString(36).substr(2, 4)}`,
              type: validMeta.type,
              label: c.label || validMeta.name,
              x: typeof c.x === 'number' ? c.x : 100,
              y: typeof c.y === 'number' ? c.y : 100,
              rotation: c.rotation || 0,
              ports: validMeta.defaultPorts.map((p) => ({ ...p, value: 0 })),
              state: { ...(validMeta.defaultState || {}), ...(c.state || {}) },
            };
          });

          // Normalize wires
          const hydratedWires = parsed.wires.map((w: any, idx: number) => ({
            id: w.id || `w_ai_${Date.now()}_${idx}`,
            fromComp: w.fromComp,
            fromPort: w.fromPort || 'out',
            toComp: w.toComp,
            toPort: w.toPort || 'in0',
            state: 0 as const,
          }));

          const synthCircuit: CircuitData = {
            id: `circuit_ai_${Date.now()}`,
            title: parsed.title || 'ConstructLab Synthesized Circuit',
            description: parsed.description || 'Generated by ConstructLab AI Tutor',
            components: hydratedComponents,
            wires: hydratedWires,
            zoom: 1,
            pan: { x: 0, y: 0 },
          };

          return { cleanText: text, circuit: synthCircuit };
        }
      } catch (err) {
        console.warn('Could not parse circuit JSON from AI response:', err);
      }
    }
    return { cleanText: text };
  };

  const handleSend = async (customPrompt?: string) => {
    const messageText = customPrompt || input.trim();
    if (!messageText || loading) return;

    const userMessage: ChatMessage = {
      id: `user_${Date.now()}`,
      role: 'user',
      content: messageText,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    };

    const newMessages = [...messages, userMessage];
    setMessages(newMessages);
    if (!customPrompt) setInput('');
    setLoading(true);

    try {
      // Prepare request payload
      const historyPayload = newMessages
        .filter((m) => m.id !== 'welcome')
        .map((m) => ({ role: m.role, content: m.content }));

      const circuitContext = {
        title: circuit.title,
        components: circuit.components.map((c) => ({
          id: c.id,
          type: c.type,
          label: c.label,
          state: c.state,
        })),
        wires: circuit.wires,
      };

      let replyText = '';
      let extractedCircuit: CircuitData | undefined;

      try {
        const res = await fetch('/api/ai/chat', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            messages: historyPayload,
            circuitContext,
          }),
        });

        const data = await res.json();
        if (res.ok && data.reply) {
          replyText = data.reply;
        } else {
          // If server failed (e.g. 503 high demand), check client synthesizer
          const localFallback = synthesizeLocalCircuit(messageText, circuit);
          if (localFallback) {
            replyText = localFallback.reply;
            extractedCircuit = localFallback.circuit;
          } else {
            throw new Error(data.error || 'Failed to get response from AI Tutor');
          }
        }
      } catch (networkErr: any) {
        const localFallback = synthesizeLocalCircuit(messageText, circuit);
        if (localFallback) {
          replyText = localFallback.reply;
          extractedCircuit = localFallback.circuit;
        } else {
          throw networkErr;
        }
      }

      if (!extractedCircuit) {
        const extracted = extractCircuitFromResponse(replyText);
        replyText = extracted.cleanText;
        extractedCircuit = extracted.circuit;
      }

      const assistantMessage: ChatMessage = {
        id: `assistant_${Date.now()}`,
        role: 'assistant',
        content: replyText,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
        circuitPayload: extractedCircuit,
      };

      setMessages((prev) => [...prev, assistantMessage]);
    } catch (err: any) {
      const errorMessage: ChatMessage = {
        id: `err_${Date.now()}`,
        role: 'assistant',
        content: `⚠️ **Notice**: The remote AI service is temporarily experiencing high traffic load. You can click on the suggestion chips above (such as "Build a 2-bit Adder", "Explain K-Maps", etc.) or ask circuit design questions like *"design an AND gate circuit"*!`,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      };
      setMessages((prev) => [...prev, errorMessage]);
    } finally {
      setLoading(false);
    }
  };

  const handleKeyDown = (e: React.KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSend();
    }
  };

  const handleCopy = (id: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  const handleLoadCircuit = (circuitPayload: CircuitData, messageId: string) => {
    onSynthesizeCircuit(circuitPayload);
    setLoadedCircuitId(messageId);
    setTimeout(() => setLoadedCircuitId(null), 3000);
  };

  const handleClearChat = () => {
    setMessages([
      {
        id: 'welcome',
        role: 'assistant',
        content: `### ConstructLab AI Tutor 🤖⚡
Conversation history cleared. How can I help you next with your digital logic designs?`,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      },
    ]);
  };

  return (
    <div className="fixed inset-0 bg-slate-950/75 backdrop-blur-sm z-50 flex items-center justify-center p-2 sm:p-4 animate-in fade-in duration-150">
      <div
        className={`w-full max-w-3xl h-[92vh] sm:h-[88vh] max-h-[850px] rounded-2xl border shadow-2xl flex flex-col overflow-hidden transition-colors ${
          isDarkMode ? 'bg-slate-900 border-slate-800 text-slate-100' : 'bg-white border-slate-200 text-slate-900'
        }`}
      >
        {/* Modal Top Header */}
        <div
          className={`px-4 py-3 border-b flex items-center justify-between shrink-0 ${
            isDarkMode ? 'bg-slate-900/90 border-slate-800' : 'bg-slate-50 border-slate-200'
          }`}
        >
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-blue-600 to-indigo-500 flex items-center justify-center text-white shadow-md shadow-blue-500/20 shrink-0">
              <Bot className="w-4.5 h-4.5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className={`font-bold text-sm leading-tight ${isDarkMode ? 'text-white' : 'text-slate-900'}`}>
                  ConstructLab AI Tutor
                </h2>
                <span className="text-[10px] px-1.5 py-0.5 rounded bg-blue-500/10 text-blue-500 font-mono font-bold border border-blue-500/20">
                  Gemini 3.7
                </span>
              </div>
              <p className={`text-[11px] leading-tight ${isDarkMode ? 'text-slate-400' : 'text-slate-600'}`}>
                Active Canvas: <span className="font-semibold text-blue-500">{circuit.title || 'Untitled Circuit'}</span>{' '}
                ({circuit.components.length} components, {circuit.wires.length} wires)
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1.5">
            <button
              onClick={handleClearChat}
              className={`p-1.5 rounded-lg text-xs transition-colors flex items-center gap-1 ${
                isDarkMode ? 'text-slate-400 hover:text-slate-200 hover:bg-slate-800' : 'text-slate-500 hover:text-slate-800 hover:bg-slate-200'
              }`}
              title="Clear Conversation"
            >
              <Trash2 className="w-4 h-4" />
              <span className="hidden md:inline text-[11px]">Clear</span>
            </button>
            <button
              onClick={onClose}
              className={`p-1.5 rounded-lg transition-colors ${
                isDarkMode ? 'text-slate-400 hover:text-slate-200 hover:bg-slate-800' : 'text-slate-500 hover:text-slate-800 hover:bg-slate-200'
              }`}
              title="Close AI Tutor"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Quick Suggestion Chips */}
        <div
          className={`px-3 py-2 border-b flex items-center gap-1.5 overflow-x-auto no-scrollbar shrink-0 text-xs ${
            isDarkMode ? 'bg-slate-950/40 border-slate-800/80' : 'bg-slate-100/70 border-slate-200'
          }`}
        >
          <span className={`text-[10px] font-semibold uppercase tracking-wider shrink-0 mr-1 ${isDarkMode ? 'text-slate-500' : 'text-slate-600'}`}>
            Suggestions:
          </span>
          {QUICK_PROMPTS.map((prompt, idx) => (
            <button
              key={idx}
              onClick={() => handleSend(prompt)}
              disabled={loading}
              className={`px-2.5 py-1 rounded-full text-[11px] font-medium whitespace-nowrap transition-all border shrink-0 ${
                isDarkMode
                  ? 'bg-slate-800/80 hover:bg-blue-600/20 text-slate-300 hover:text-blue-400 border-slate-700/80 hover:border-blue-500/40'
                  : 'bg-white hover:bg-blue-50 text-slate-700 hover:text-blue-700 border-slate-300 hover:border-blue-300 shadow-2xs'
              } disabled:opacity-50`}
            >
              {prompt}
            </button>
          ))}
        </div>

        {/* Chat Messages Log Area */}
        <div className="flex-1 overflow-y-auto p-3 sm:p-4 space-y-4">
          {messages.map((msg) => {
            const isAssistant = msg.role === 'assistant';
            return (
              <div
                key={msg.id}
                className={`flex gap-2.5 sm:gap-3 ${isAssistant ? 'justify-start' : 'justify-end'} animate-in fade-in duration-200`}
              >
                {/* Assistant Avatar */}
                {isAssistant && (
                  <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-blue-600 flex items-center justify-center text-white shrink-0 shadow-sm mt-0.5">
                    <Bot className="w-4 h-4" />
                  </div>
                )}

                {/* Message Bubble Container */}
                <div className={`flex flex-col max-w-[85%] sm:max-w-[78%] ${isAssistant ? 'items-start' : 'items-end'}`}>
                  <div
                    className={`rounded-2xl px-3.5 py-2.5 sm:px-4 sm:py-3 text-xs sm:text-[13px] leading-relaxed shadow-sm relative group ${
                      isAssistant
                        ? isDarkMode
                          ? 'bg-slate-800/90 text-slate-200 border border-slate-700/70 rounded-tl-sm'
                          : 'bg-slate-100 text-slate-800 border border-slate-200/90 rounded-tl-sm'
                        : 'bg-blue-600 text-white rounded-tr-sm'
                    }`}
                  >
                    {/* Markdown Body */}
                    <div className="markdown-body select-text">
                      <ReactMarkdown
                        components={{
                          h1: ({ children }) => <h1 className="text-sm sm:text-base font-bold my-1 text-inherit">{children}</h1>,
                          h2: ({ children }) => <h2 className="text-xs sm:text-sm font-bold my-1 text-inherit">{children}</h2>,
                          h3: ({ children }) => <h3 className="text-xs sm:text-xs font-bold my-1 text-inherit">{children}</h3>,
                          p: ({ children }) => <p className="my-1.5 leading-relaxed">{children}</p>,
                          ul: ({ children }) => <ul className="list-disc pl-4 my-1.5 space-y-1">{children}</ul>,
                          ol: ({ children }) => <ol className="list-decimal pl-4 my-1.5 space-y-1">{children}</ol>,
                          li: ({ children }) => <li className="leading-relaxed">{children}</li>,
                          code: ({ children }) => (
                            <code className={`px-1 py-0.5 rounded font-mono text-[11px] ${
                              isAssistant
                                ? isDarkMode ? 'bg-slate-900 text-blue-300' : 'bg-slate-200 text-blue-700'
                                : 'bg-blue-700 text-blue-100'
                            }`}>
                              {children}
                            </code>
                          ),
                          pre: ({ children }) => (
                            <pre className={`p-2.5 rounded-lg my-2 overflow-x-auto font-mono text-[11px] ${
                              isDarkMode ? 'bg-slate-950 text-slate-200 border border-slate-800' : 'bg-slate-900 text-slate-100'
                            }`}>
                              {children}
                            </pre>
                          ),
                          strong: ({ children }) => <strong className="font-semibold">{children}</strong>,
                          blockquote: ({ children }) => (
                            <blockquote className={`pl-3 border-l-2 my-2 italic ${
                              isDarkMode ? 'border-blue-400 text-slate-400' : 'border-blue-600 text-slate-600'
                            }`}>
                              {children}
                            </blockquote>
                          ),
                        }}
                      >
                        {msg.content}
                      </ReactMarkdown>
                    </div>

                    {/* Interactive Circuit Synthesis Action Card */}
                    {msg.circuitPayload && (
                      <div
                        className={`mt-3 p-3 rounded-xl border flex flex-col sm:flex-row items-start sm:items-center justify-between gap-2.5 ${
                          isDarkMode
                            ? 'bg-slate-900/90 border-blue-500/40 text-slate-200'
                            : 'bg-blue-50/80 border-blue-300 text-slate-800'
                        }`}
                      >
                        <div className="flex items-center gap-2">
                          <div className="w-7 h-7 rounded-lg bg-blue-500/20 text-blue-500 flex items-center justify-center shrink-0">
                            <Cpu className="w-4 h-4" />
                          </div>
                          <div>
                            <div className="font-bold text-xs">{msg.circuitPayload.title || 'Synthesized Circuit'}</div>
                            <div className={`text-[10px] ${isDarkMode ? 'text-slate-400' : 'text-slate-600'}`}>
                              {msg.circuitPayload.components.length} components, {msg.circuitPayload.wires.length} connections ready
                            </div>
                          </div>
                        </div>

                        <button
                          onClick={() => handleLoadCircuit(msg.circuitPayload!, msg.id)}
                          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold transition-all shadow-sm shrink-0 ${
                            loadedCircuitId === msg.id
                              ? 'bg-emerald-600 text-white'
                              : 'bg-blue-600 hover:bg-blue-500 text-white shadow-blue-600/20'
                          }`}
                        >
                          {loadedCircuitId === msg.id ? (
                            <>
                              <CheckCircle2 className="w-3.5 h-3.5" />
                              <span>Loaded to Canvas!</span>
                            </>
                          ) : (
                            <>
                              <ArrowDownToLine className="w-3.5 h-3.5" />
                              <span>Load to Canvas</span>
                            </>
                          )}
                        </button>
                      </div>
                    )}

                    {/* Copy Button */}
                    <button
                      onClick={() => handleCopy(msg.id, msg.content)}
                      className={`absolute top-2 right-2 p-1 rounded opacity-0 group-hover:opacity-100 transition-opacity ${
                        isAssistant
                          ? isDarkMode ? 'hover:bg-slate-700 text-slate-400' : 'hover:bg-slate-200 text-slate-500'
                          : 'hover:bg-blue-700 text-blue-100'
                      }`}
                      title="Copy response"
                    >
                      {copiedId === msg.id ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                    </button>
                  </div>

                  {/* Message Timestamp */}
                  <span className={`text-[9px] mt-1 px-1 ${isDarkMode ? 'text-slate-500' : 'text-slate-400'}`}>
                    {msg.timestamp}
                  </span>
                </div>

                {/* User Avatar */}
                {!isAssistant && (
                  <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-slate-700 flex items-center justify-center text-slate-200 shrink-0 shadow-sm mt-0.5">
                    <User className="w-4 h-4" />
                  </div>
                )}
              </div>
            );
          })}

          {/* Loading Indicator Bubble */}
          {loading && (
            <div className="flex gap-2.5 sm:gap-3 justify-start animate-in fade-in duration-150">
              <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-blue-600 flex items-center justify-center text-white shrink-0 shadow-sm">
                <Bot className="w-4 h-4" />
              </div>
              <div
                className={`rounded-2xl rounded-tl-sm px-4 py-3 text-xs flex items-center gap-2 border ${
                  isDarkMode
                    ? 'bg-slate-800/90 border-slate-700 text-slate-300'
                    : 'bg-slate-100 border-slate-200 text-slate-700'
                }`}
              >
                <Loader2 className="w-4 h-4 animate-spin text-blue-500" />
                <span className="font-medium">ConstructLab AI is analyzing your circuit...</span>
              </div>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* Input Bar & Footer */}
        <div
          className={`p-3 sm:p-4 border-t shrink-0 ${
            isDarkMode ? 'bg-slate-900/95 border-slate-800' : 'bg-slate-50 border-slate-200'
          }`}
        >
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSend();
            }}
            className="flex items-end gap-2"
          >
            <div className="relative flex-1">
              <textarea
                ref={inputRef}
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onKeyDown={handleKeyDown}
                placeholder="Ask AI Tutor anything (e.g. 'Explain my circuit', 'Design a Full Adder', 'Why is LED off?')..."
                rows={1}
                className={`w-full px-3.5 py-2.5 max-h-28 text-xs sm:text-[13px] rounded-xl border transition-all resize-none outline-none ${
                  isDarkMode
                    ? 'bg-slate-800 border-slate-700 text-slate-100 placeholder-slate-500 focus:border-blue-500 focus:ring-1 focus:ring-blue-500'
                    : 'bg-white border-slate-300 text-slate-900 placeholder-slate-400 focus:border-blue-500 focus:ring-1 focus:ring-blue-500'
                }`}
                style={{ minHeight: '42px' }}
              />
            </div>

            <button
              type="submit"
              disabled={!input.trim() || loading}
              className={`h-[42px] px-4 rounded-xl font-semibold text-xs flex items-center justify-center gap-1.5 transition-all shrink-0 ${
                input.trim() && !loading
                  ? 'bg-blue-600 hover:bg-blue-500 text-white shadow-md shadow-blue-600/20 cursor-pointer active:scale-95'
                  : 'bg-slate-800 text-slate-500 border border-slate-700 cursor-not-allowed opacity-60'
              }`}
              title="Send Message (Enter)"
            >
              {loading ? (
                <Loader2 className="w-4 h-4 animate-spin" />
              ) : (
                <>
                  <span className="hidden sm:inline">Send</span>
                  <Send className="w-3.5 h-3.5" />
                </>
              )}
            </button>
          </form>

          <div className="flex items-center justify-between mt-2 px-1 text-[10px] text-slate-500">
            <span>Press <strong>Enter</strong> to send, <strong>Shift+Enter</strong> for new line</span>
            <span>Powered by Gemini 3.7</span>
          </div>
        </div>
      </div>
    </div>
  );
};
